const file = name => new URL(`../${name}`,import.meta.url);
async function writeFile(destination,value) {
  const expected = typeof value==='string'?Buffer.from(value):value;
  try {
    if((await readFile(destination)).equals(expected)) return;
  } catch(error) {
    if(error.code!=='ENOENT') throw error;
  }
  await saveFile(destination,expected);
}
